#!/usr/bin/env python3
"""Both pages from one component (src/dash.js): the lock screen's block (early.html)
and the app's page (index.html) -- run after changing it."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent / 'aiquota'
dash = (HERE / 'dash.js').read_text()

early = '''<script>/* BEGIN e5-aiquota (the aiquota app, /etc/e5-infoscreen/plugins/aiquota) */
// The lock screen's second page, quota-tray's dashboard: right opens it over the clock, then
// left/right the kinds, up/down the accounts, OK an account's details; left on "全部" or back
// returns to the clock; dark or unlocked, it is the clock again.  Before power-menu.js and
// mobile.js: mobile.js takes every other key on the lock screen.  Without the app (GET /quota
// 404) this does nothing.  Generated by src/build.py from src/dash.js.
(function () {
	const API = '/api/plugins/aiquota';
	let gone = false, panel = null, dash = null, open = false, timer = null;
''' + dash + '''
	const lockShown = () => {
		const ls = document.getElementById('mobile-lockscreen');
		return !!ls && !ls.hidden && document.body.classList.contains('screen-locked') && !(typeof blank !== 'undefined' && blank);
	};
	function ensure() {
		if (panel?.isConnected) return panel;
		const ls = document.getElementById('mobile-lockscreen');
		if (!ls) return null;
		if (!document.getElementById('lock-quota-css')) {
			const css = document.createElement('style');
			css.id = 'lock-quota-css';
			css.textContent = '#lock-quota,#lock-quota *{box-sizing:border-box}#lock-quota{position:absolute;inset:0;z-index:5;background:#090a0f;color:#f3f6fa;' +
				'padding:10px 10px 6px;overflow-y:auto;scrollbar-width:none;font:13px/1.45 "Noto Sans CJK SC",sans-serif}' + DCSS;
			document.head.appendChild(css);
		}
		panel = document.createElement('div');
		panel.id = 'lock-quota';
		panel.hidden = true;
		ls.appendChild(panel);
		dash = Dash(panel, refreshNow);
		return panel;
	}
	let since = null, until = 0;
	function refreshNow() {
		// the NAS fetches everything again (some 30-40 s); followed until the data is newer
		fetch(API + '/refresh', { method: 'POST', cache: 'no-store' }).then((r) => r.json()).then((d) => {
			since = d.before ?? 0; until = Date.now() + 120000;
			dash.refreshing(true); load();
		}, () => {});
	}
	function load() {
		clearTimeout(timer);
		fetch(API + '/quota' + (since != null ? '?fresh=1' : ''), { cache: 'no-store' }).then((r) => {
			if (r.status == 404) { gone = true; close(); return null; }
			return r.json().catch(() => null);
		}).then((d) => {
			if (gone || !open) return;
			const waiting = since != null && Date.now() < until && !((d?.generated_at_ms ?? 0) > since);
			if (since != null && !waiting) { since = null; dash.refreshing(false); }
			// (the next refresh is set first: odd data must not stop it for good)
			timer = setTimeout(load, !d?.accounts || waiting ? 3000 : 60000);
			if (d?.accounts) try { dash.set(d); } catch (e) { console.log('aiquota: ' + e); }
			else if (d?.error) panel.innerHTML = `<div class="dempty">${esc(d.error)}</div>`;
		}, () => { if (open) timer = setTimeout(load, 5000); });
	}
	function show() {
		if (!ensure()) return;
		open = true;
		panel.hidden = false;
		dash.reset();
		load();
	}
	function close() {
		open = false;
		clearTimeout(timer);
		if (panel) panel.hidden = true;
	}
	const KIND = { ArrowLeft: 'left', ArrowRight: 'right', ArrowUp: 'up', ArrowDown: 'down', Enter: 'ok', Escape: 'back', Backspace: 'back' };
	window.addEventListener('keydown', (e) => {
		if (gone || !lockShown()) return;
		const kind = KIND[e.key];
		if (!kind) return;
		if (!open) {
			if (kind != 'right') return;
			show();
		} else if (kind == 'back' || (kind == 'left' && dash.onFirstTab())) close();
		else if (!dash.key(kind)) return;
		e.preventDefault();
		e.stopImmediatePropagation();
	}, true);
	// (each wake starts on the clock)
	setInterval(() => { if (open && !lockShown()) close(); }, 700);
})();
/* END e5-aiquota */</script>
'''
(APP / 'early.html').write_text(early)

index = '''<!doctype html>
<html lang="zh">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,user-scalable=no">
<title>配额</title>
<style>
	:root { color-scheme: dark; }
	* { box-sizing: border-box; }
	html, body { margin: 0; height: 100%; overflow: hidden; background: #090a0f; color: #f3f6fa;
		font: 13px/1.45 "Noto Sans CJK SC", "DejaVu Sans", sans-serif; cursor: none; user-select: none; }
	#root { height: 100%; overflow-y: auto; scrollbar-width: none; padding: 8px 10px 4px; }
</style>
</head>
<body>
<div id="root"></div>
<!-- generated by src/build.py from src/dash.js -->
<script src="/sdk/e5.js"></script>
<script>
'use strict';
''' + dash + '''
const style = document.createElement('style');
style.textContent = DCSS;
document.head.appendChild(style);
let since = null, until = 0, timer = null;
async function refreshNow() {
	try { const d = await e5.api('/refresh', { method: 'POST' }); since = d.before ?? 0; until = Date.now() + 120000; dash.refreshing(true); load(); }
	catch (e) { console.log('aiquota: ' + e); }
}
const dash = Dash(document.getElementById('root'), refreshNow);
dash.reset();
async function load() {
	clearTimeout(timer);
	let d = null;
	try { d = await e5.api('/quota' + (since != null ? '?fresh=1' : '')); } catch (e) { document.getElementById('root').innerHTML = `<div class="dempty">${esc(e.message || e)}</div>`; }
	const waiting = since != null && Date.now() < until && !((d?.generated_at_ms ?? 0) > since);
	if (since != null && !waiting) { since = null; dash.refreshing(false); }
	timer = setTimeout(load, !d?.accounts || waiting ? 3000 : 60000);
	if (d?.accounts) try { dash.set(d); } catch (e) { console.log('aiquota: ' + e); }
}
e5.onKey((k) => dash.key(k.kind));
load();
</script>
</body>
</html>
'''
(APP / 'index.html').write_text(index)
print('built early.html and index.html')
